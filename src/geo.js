  /** 공항 좌표. 모르면 나라 가운데로, 그것도 모르면 null. */
  function coordOf(iata) {
    if (!iata) return null;
    var code = String(iata).toUpperCase();
    if (COORD[code]) return { lat: COORD[code].lat, lon: COORD[code].lon, exact: true };
    var country = airports ? airports.countryOf(code) : null;
    var center = country && COUNTRY_CENTER[country];
    if (!center) return null;
    return { lat: center[0], lon: center[1], exact: false };
  }

  /** 두 지점 사이 대권 거리(km). */
  function distanceKm(a, b) {
    if (!a || !b) return 0;
    var dLat = (b.lat - a.lat) * RAD;
    var dLon = (b.lon - a.lon) * RAD;
    var s = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(a.lat * RAD) * Math.cos(b.lat * RAD) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
    return 2 * EARTH_KM * Math.asin(Math.min(1, Math.sqrt(s)));
  }

  /** 지구 몇 바퀴인지. */
  function laps(km) {
    return km / EQUATOR_KM;
  }

  /** 가운데 경도를 기준으로 -180~180 안에 들어오게 접는다. */
  function wrapLon(lon, center) {
    var value = lon - (center || 0);
    while (value > 180) value -= 360;
    while (value < -180) value += 360;
    return value;
  }

  /**
   * 지도 위의 자리. 가로는 경도 그대로, 세로는 위도 그대로 펴는 방식(등장방형).
   * 남극과 북극 끝은 비행할 일이 없어 위아래를 잘라 쓴다.
   * center 를 주면 그 경도가 지도 한가운데로 온다. 한국을 가운데 두면
   * 태평양 노선이 화면을 가로질러 잘리지 않는다.
   */
  function project(point, size) {
    var box = size || { width: 1, height: 1 };
    var top = box.top == null ? 84 : box.top;
    var bottom = box.bottom == null ? -60 : box.bottom;
    return {
      x: ((wrapLon(point.lon, box.center) + 180) / 360) * box.width,
      y: ((top - point.lat) / (top - bottom)) * box.height
    };
  }

  /**
   * 두 공항을 잇는 대권 항로를 점으로 쪼갠다. 지도에 그리면 자연스레 휜다.
   * 지도 끝을 넘어가면 선이 화면을 가로지르지 않도록 토막을 나눠 준다.
   * center 는 project 에 준 것과 같은 값을 줘야 끊기는 자리가 맞는다.
   */
  function arc(a, b, steps, center) {
    if (!a || !b) return [];
    var n = steps || 48;
    var lat1 = a.lat * RAD, lon1 = a.lon * RAD;
    var lat2 = b.lat * RAD, lon2 = b.lon * RAD;
    var d = 2 * Math.asin(Math.sqrt(
      Math.pow(Math.sin((lat1 - lat2) / 2), 2) +
      Math.cos(lat1) * Math.cos(lat2) * Math.pow(Math.sin((lon1 - lon2) / 2), 2)
    ));
    if (!d) return [[{ lat: a.lat, lon: a.lon }]];

    var line = [];
    for (var i = 0; i <= n; i++) {
      var f = i / n;
      var A = Math.sin((1 - f) * d) / Math.sin(d);
      var B = Math.sin(f * d) / Math.sin(d);
      var x = A * Math.cos(lat1) * Math.cos(lon1) + B * Math.cos(lat2) * Math.cos(lon2);
      var y = A * Math.cos(lat1) * Math.sin(lon1) + B * Math.cos(lat2) * Math.sin(lon2);
      var z = A * Math.sin(lat1) + B * Math.sin(lat2);
      line.push({
        lat: Math.atan2(z, Math.sqrt(x * x + y * y)) / RAD,
        lon: Math.atan2(y, x) / RAD
      });
    }

    var pieces = [[line[0]]];
    for (var k = 1; k < line.length; k++) {
      var prev = line[k - 1];
      var here = line[k];
      // 지도 왼쪽 끝에서 오른쪽 끝으로 튀었으면 거기서 끊는다
      if (Math.abs(wrapLon(here.lon, center) - wrapLon(prev.lon, center)) > 180) pieces.push([]);
      pieces[pieces.length - 1].push(here);
    }
    return pieces.filter(function (piece) { return piece.length > 1; });
  }

  return {
    COORD: COORD,
    COUNTRY_CENTER: COUNTRY_CENTER,
    EQUATOR_KM: EQUATOR_KM,
    coordOf: coordOf,
    distanceKm: distanceKm,
    laps: laps,
    project: project,
    wrapLon: wrapLon,
    arc: arc
  };
